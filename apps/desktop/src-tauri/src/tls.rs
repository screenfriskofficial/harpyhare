//! Единственная точка установки криптопровайдера rustls.
//!
//! reqwest собран с `rustls-no-provider` (см. Cargo.toml), а tokio-tungstenite
//! провайдера не выбирает вовсе — поэтому `rustls` 0.23 требует, чтобы
//! процесс назначил его ЯВНО до первого TLS-клиента. Раньше это делал только
//! `setup_app`, и любой код, живущий вне запуска приложения (тесты, примеры,
//! смоуки), падал на сборке `reqwest::Client` с паникой про отсутствующий
//! провайдер. Теперь каждый конструктор клиента зовёт `ensure_crypto_provider`
//! сам: вызов идемпотентен и после первого раза стоит одну атомарную проверку.

use std::sync::Once;

static INSTALL: Once = Once::new();

/// Ставит `ring` провайдером по умолчанию, если этого ещё никто не сделал.
///
/// Ошибка `install_default` («уже установлен») намеренно игнорируется: другой
/// код процесса мог назначить провайдера раньше, и это не повод падать.
pub fn ensure_crypto_provider() {
    INSTALL.call_once(|| {
        let _ = rustls::crypto::ring::default_provider().install_default();
    });
}
